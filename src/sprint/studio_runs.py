"""Local run ownership and bounded record access for Sprint Studio."""

import asyncio
import codecs
import json
from datetime import UTC, datetime
from pathlib import Path
from uuid import uuid4

from sprint.cli.env import load_experiment


def read_json(path):
    """Only read small, regular operator records; never follow artifact links."""
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 2 * 1024**2:
        return None
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


class StudioRuns:
    """Own tasks in this server process; never restart unknown work implicitly."""

    def __init__(self, directory):
        self.directory = Path(directory).resolve()
        self.tasks = {}

    def root(self, identity):
        if len(identity) != 32 or any(c not in "0123456789abcdef" for c in identity):
            raise ValueError("invalid run identifier")
        root = self.directory / identity
        if root.is_symlink() or not root.is_dir():
            raise FileNotFoundError("run not found")
        return root

    def write(self, root, **values):
        state = read_json(root / "studio-run.json") or {}
        state.update(values, updated_at=datetime.now(UTC).isoformat())
        temporary = root / ".studio-run.tmp"
        temporary.write_text(json.dumps(state, allow_nan=False))
        temporary.replace(root / "studio-run.json")
        return state

    def snapshot(self, identity):
        root = self.root(identity)
        state = read_json(root / "studio-run.json")
        if not isinstance(state, dict):
            raise ValueError("run record is unreadable")
        if (
            state["status"] in {"queued", "running", "cancelling"}
            and identity not in self.tasks
        ):
            state = {
                **state,
                "status": "unknown",
                "error": "The owning server is unavailable. Provider work may still exist; inspect cleanup records before retrying.",
            }
        records = root / "records"
        return {
            **state,
            "result": read_json(records / "result.json"),
            "cleanup_errors": read_json(records / "cleanup-errors.json"),
            "interruption": read_json(records / "interruption.json"),
        }

    def list(self):
        if not self.directory.exists():
            return []
        result = []
        for path in sorted(self.directory.iterdir(), reverse=True):
            try:
                value = self.snapshot(path.name)
                result.append(
                    {
                        k: v
                        for k, v in value.items()
                        if k not in {"result", "interruption"}
                    }
                )
            except (ValueError, FileNotFoundError):
                continue
        return sorted(result, key=lambda row: row["started_at"], reverse=True)

    def start(self, draft, files, backend):
        if any(not task.done() for task in self.tasks.values()):
            raise ValueError(
                "One Studio trial can run at a time. Finish or cancel it first."
            )
        identity = uuid4().hex
        root = self.directory / identity
        root.mkdir(parents=True, mode=0o700)
        project = root / "project"
        project.mkdir()
        for name, content in files.items():
            path = project / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        # environment.py is generated by Studio, not arbitrary uploaded Python.
        # The authored private verifier is executed only by Sprint validation.
        experiment = load_experiment(project)
        self.write(
            root,
            id=identity,
            name=draft.name,
            status="queued",
            backend=backend,
            started_at=datetime.now(UTC).isoformat(),
            model=draft.model,
            minutes=draft.minutes,
            records=str(root / "records"),
        )

        async def execute():
            self.write(root, status="running")
            try:
                result = await experiment.run(
                    directory=root / "records", backend=backend
                )
            except asyncio.CancelledError:
                self.write(root, status="cancelled")
                raise
            except Exception as error:
                self.write(
                    root, status="failed", error=f"{type(error).__name__}: {error}"
                )
            else:
                failed = not result.trials or any(
                    trial.status in {"error", "cancelled", "interrupted"}
                    for trial in result.trials
                )
                self.write(root, status="failed" if failed else "completed")

        task = asyncio.create_task(execute(), name="studio-" + identity)
        self.tasks[identity] = task

        def finished(task):
            if task.cancelled():
                self.write(root, status="cancelled")
            self.tasks.pop(identity, None)

        task.add_done_callback(finished)
        return self.snapshot(identity)

    def cancel(self, identity):
        root = self.root(identity)
        task = self.tasks.get(identity)
        if task is None or task.done():
            raise ValueError("This server does not own a running task with that ID")
        state = self.write(root, status="cancelling")
        task.cancel()
        return state

    async def close(self):
        tasks = list(self.tasks.values())
        for task in tasks:
            task.cancel()
        await asyncio.gather(*tasks, return_exceptions=True)

    def sources(self, identity):
        """Only expose known public record channels, never service state or keys."""
        root = self.root(identity) / "records"
        sources = {
            "agent": root / "agent-events.jsonl",
            "lifecycle": root / "events.jsonl",
        }
        # Deliberate resource evidence only, not private service working files.
        resources = root / "resources"
        if resources.is_dir() and not resources.is_symlink():
            for trial in resources.iterdir():
                if trial.is_symlink() or not trial.is_dir():
                    continue
                for journal in trial.glob("*/jobs.jsonl"):
                    if not journal.parent.is_symlink():
                        sources["worker:" + str(journal.relative_to(resources))] = (
                            journal
                        )
        # Older runs may predate live capture. Show their collected native log
        # rather than displaying an empty transcript after an execution failure.
        if not sources["agent"].is_file():
            result = read_json(root / "result.json") or {}
            for trial in result.get("trials", []):
                relative = Path(trial.get("records", ""))
                if relative.is_absolute() or ".." in relative.parts:
                    continue
                directory = root / relative / "agent"
                if any(path.is_symlink() for path in (root / relative, directory)):
                    continue
                for name in ("codex.txt", "claude-code.txt", "oracle.txt"):
                    path = directory / name
                    if path.is_file() and not path.is_symlink():
                        sources["native:" + str(path.relative_to(root))] = path
        return sources


def tail_text(path, offset):
    """Legacy collected output has no inferred timestamps."""
    if offset < 0:
        raise ValueError("cursor must be nonnegative")
    if path.is_symlink() or not path.is_file():
        return {"cursor": 0, "events": []}
    if offset > path.stat().st_size:
        offset = 0
    with path.open("rb") as source:
        source.seek(offset)
        data = source.read(65536)
        decoder = codecs.getincrementaldecoder("utf-8")(errors="replace")
        text = decoder.decode(data, final=source.tell() >= path.stat().st_size)
        remaining, _ = decoder.getstate()
    return {
        "cursor": offset + len(data) - len(remaining),
        "events": [
            {"text": text, "phase": "agent", "stream": "collected", "timestamp": None}
        ]
        if text
        else [],
    }


def tail(path, offset):
    """Read at most 256 KiB without returning partial or oversized records."""
    if offset < 0:
        raise ValueError("cursor must be nonnegative")
    if path.is_symlink() or not path.is_file():
        return {"cursor": 0, "events": []}
    size = path.stat().st_size
    if offset > size:
        offset = 0
    events = []
    with path.open("rb") as source:
        source.seek(offset)
        start = offset
        while source.tell() - start < 256 * 1024:
            position = source.tell()
            line = source.readline(2 * 1024**2 + 1)
            if not line or not line.endswith(b"\n"):
                source.seek(position)
                break
            if len(line) > 2 * 1024**2:
                raise ValueError("log record exceeds the viewer limit")
            try:
                events.append(json.loads(line))
            except ValueError:
                events.append(
                    {
                        "event": "record-error",
                        "text": "Malformed journal line",
                        "offset": position,
                    }
                )
        cursor = source.tell()
    return {"cursor": cursor, "events": events}
